import unittest

import reugin.rhtml as h
from reugin.unjustpython import UnjustContext, UnjustPythonTranslator


class RHTMLTests(unittest.TestCase):
    def test_escaping_and_attributes(self) -> None:
        tag = h.a('<b> & "q"', href='/x?a=1&b="2"', class_="link", data_id=5, hidden=True, title=None)
        self.assertEqual(
            tag.render(),
            '<a href="/x?a=1&amp;b=&quot;2&quot;" class="link" data-id="5" hidden>&lt;b&gt; &amp; &quot;q&quot;</a>',
        )

    def test_property_children_and_skipped_values(self) -> None:
        self.assertEqual(h.div(h.PClass("card"), h.p("Hi"), None, False).render(), '<div class="card"><p>Hi</p></div>')
        self.assertEqual(h.p("Hello", h.b("world")).render(), "<p>Hello <b>world</b></p>")

    def test_void_and_raw_text(self) -> None:
        self.assertEqual(h.input(type="checkbox", checked=h.EmptyAttr()).render(), '<input type="checkbox" checked>')
        self.assertEqual(h.br().render(), "<br>")
        with self.assertRaises(ValueError):
            h.img("text").render()
        self.assertEqual(h.script("if (a < b) go();").render(), "<script>if (a < b) go();</script>")
        self.assertEqual(h.style("a > b { x: 1 }").render(), "<style>a > b { x: 1 }</style>")

    def test_bind_and_document(self) -> None:
        self.assertEqual((h.p("a") + h.p("b") + "c").render(), "<p>a</p> <p>b</p> c")
        css = h.CSSInjection("site", "/static/site.css")
        page = h.Document([h.div(css, h.p("one")), h.div(css)], [h.title("T")], lang="en")
        self.assertEqual(
            page.render(),
            '<!DOCTYPE html><html lang="en"><head><meta charset="utf-8"><title>T</title>'
            '<link href="/static/site.css" rel="stylesheet"></head>'
            "<body><div><p>one</p></div> <div></div></body></html>",
        )
        self.assertEqual(len((page + h.p("more")).body), 3)


class UnjustPythonTests(unittest.TestCase):
    def js(self, source: str) -> str:
        return UnjustPythonTranslator().generate_js_code(source)

    def test_constants(self) -> None:
        self.assertEqual(self.js("x = 1.5"), "x = 1.5")
        self.assertEqual(self.js('x = "it\'s \\"quoted\\""'), 'x = "it\'s \\"quoted\\""')
        self.assertEqual(self.js("x = [True, False, None]"), "x = [true, false, null]")

    def test_logic(self) -> None:
        self.assertEqual(
            self.js("if not a and b <= 2:\n    f(a)\nelif c:\n    g()\nelse:\n    pass"),
            "if ((!(a) && (b <= 2))) { f(a) } else { if (c) { g() } else {  } }",
        )
        self.assertEqual(self.js("x += 2 ** n"), "x += (2 ** n)")
        self.assertEqual(self.js("for i in items:\n    log(i)"), "for (const i of items) { log(i) }")
        self.assertEqual(self.js("y = [i * 2 for i in xs]"), "y = xs.map(function(i) { return (i * 2); })")

    def test_unsupported(self) -> None:
        for source in ("a < b < c", "x = a // b", "f(x=1)", "import os", "a, b = c"):
            with self.assertRaises(NotImplementedError, msg=source):
                self.js(source)

    def test_context(self) -> None:
        ctx = UnjustContext()

        @ctx.jsdef()
        def greet(name: str) -> None:
            alert("Hello, " + name)  # noqa: F821  # pyright: ignore[reportUndefinedVariable]

        ctx.include_str("const x = 1;")
        button = h.button("Hi", onclick=greet)
        self.assertEqual(button.render(), '<button onclick="greet();">Hi</button>')
        self.assertEqual(
            ctx.build_script().render(),
            '<script>/* Autogenerated */const x = 1;function greet(name) { alert(("Hello, " + name)) };</script>',
        )
        with self.assertRaises(RuntimeError):
            greet()


if __name__ == "__main__":
    unittest.main()
